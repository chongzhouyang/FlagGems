"""GCU400-specific _foreach_pow_.List (in-place) and _foreach_pow.List (out-of-place).

The common foreach executor carries the tensor list in a 2D grid, and GCU400's ``grid.y``
limit of 255 causes ``out of resource`` on large shapes. Contiguous float lists use the
1D fixed grid / metadata fused kernel from ``_foreach_flat``; non-float,
non-contiguous or broadcast shapes still delegate to the common executor to keep dtype policy and exception semantics.

The out-of-place ``.List`` overload keeps its own single-launch kernel here: the
shared ``_foreach_binary`` flat path settles on a 2-parts/16384 geometry that leaves
16 of the 48 cores idle on a sixteen-tensor list, while ``pow`` is transcendental
bound (probe ladder: the exp2/log2 math is ~75% of the runtime), so it prefers
the full 48-program grid with narrower tiles and an unmasked exact arm.
Broadcast ``.List`` forms (single-element second operands) route through the
same per-tensor broadcast layer the in-place overload uses: the shared flat
and common executors read the second list with the first list's flat index,
which is an out-of-bounds read against a one-element allocation.
"""

import logging

import torch
import triton
import triton.language as tl

from flag_gems.ops._foreach_binary import _apply_list
from flag_gems.utils import libentry
from flag_gems.utils.foreach import _device_meta

from ._foreach_binary import _apply_list as _apply_list_local
from ._foreach_binary import _pow_fn
from ._foreach_flat import (
    _TL_DTYPES,
    FALLBACK,
    MODE_LIST,
    OP_POW,
    can_use_flat,
    run_binary,
)

logger = logging.getLogger(__name__)

# --- TUNING PARAMS START ---
# Generated by the optimization iteration driver in rounds; all are compile-time/launch-time settings and do not change
# operator semantics.
# Fast-path geometry (on this machine with the new stack Triton GCU 4.1.6, 20 P×B×w combinations × 3 dtypes × 3
# core shapes interleaved with do_bench and full coverage validation per combination): P3B32768w4s1 wins with
# mean 85.8us; B65536 is rejected for exceeding the compile-time DSM limit (1.18MB > 917KB),
# and P2/P4/P5/P6 and the B16384 tier are all 4-34% worse, while stages/warps are within the noise band.
FAST_PARTS_CAP = 3
FAST_BLOCK = 32768
FAST_WARPS = 4
FAST_STAGES = 1
# out-of-place .List 快路径几何（2026-11-19 增量轮，9 cell × {P2..P6}×
# {B4k..B32k}×{w1,w2,w4,w8}×{EXACT,mask} 交错 do_bench + 探针阶梯）：
# pow 的 exp2/log2 数学占 ~75% 运行时（L0 地板 1024^2 16-bit 28.5µs vs
# 全算 122µs），几何取满 48 program 的 P3、窄 tile B8192 与 EXACT 免 mask
# 双臂；w2 对 w4 一致 -7~-10%（w1/w8 劣化），s2 与 s1 噪声带内取简。
# 逐 combo 16-tensor 全量值校验（含 300^2 ragged masked 臂）全 PASS。
OOP_PARTS_CAP = 3
OOP_BLOCK = 8192
OOP_WARPS = 2
OOP_STAGES = 1
# 第二层广播路径（run_binary）几何，沿用历史定档。
FIXED_GRID = 48
BLOCK_SIZE = 1024
NUM_WARPS = 4
NUM_STAGES = 1
USE_DEVICE_CONTEXT = 0
FP32_PROMOTE = 1
FUSED_LAUNCH = 1
FALLBACK_TO_PUBLIC = 0
# --- TUNING PARAMS END ---

# GCU400 grid.x hard limit; the fast-path grid = nt * parts must stay entirely within the limit.
_MAX_GRID_X = 65535


@libentry()
@triton.jit
def fused_pow_list_ip_kernel(
    meta_ptr,
    fn: tl.constexpr,
    NT: tl.constexpr,
    A_DT: tl.constexpr,
    BLOCK: tl.constexpr,
    PARTS: tl.constexpr,
):
    """一次 launch 对整个配对列表做 in-place ``self ** other``。

    ``meta_ptr`` 依次存放输入、第二操作数、输出（in-place 下即输入）
    地址与各元素数（各 NT 项，int64）。grid 按 ``(tensor, part)`` 线性
    展开且恒为 ``NT * PARTS``：每个 tensor 的 ``PARTS`` 个 program 以
    ``PARTS`` 为步长分摊 tile，覆盖洞按构造不存在。
    """
    pid = tl.program_id(0)
    tensor_id = pid % NT
    part_id = pid // NT

    a_ptr = tl.load(meta_ptr + tensor_id).to(tl.pointer_type(A_DT))
    b_ptr = tl.load(meta_ptr + NT + tensor_id).to(tl.pointer_type(A_DT))
    out_ptr = tl.load(meta_ptr + 2 * NT + tensor_id).to(tl.pointer_type(A_DT))
    n_elements = tl.load(meta_ptr + 3 * NT + tensor_id)

    arange = tl.arange(0, BLOCK)
    # Keep the tile count as i32, consistent with the address-arithmetic width of the common executor.
    num_tiles = tl.cdiv(n_elements, BLOCK).to(tl.int32)
    for block_id in tl.range(part_id, num_tiles, PARTS):
        idx = block_id * BLOCK + arange
        mask = idx < n_elements
        a = tl.load(a_ptr + idx, mask=mask, other=0)
        b = tl.load(b_ptr + idx, mask=mask, other=0)
        tl.store(out_ptr + idx, fn(a, b).to(A_DT), mask=mask)


@libentry()
@triton.jit
def fused_pow_list_kernel(
    meta_ptr,
    fn: tl.constexpr,
    NT: tl.constexpr,
    A_DT: tl.constexpr,
    EXACT: tl.constexpr,
    BLOCK: tl.constexpr,
    PARTS: tl.constexpr,
):
    """一次 launch 对整个配对列表做 out-of-place ``self ** other``。

    与 in-place 版共用 ``meta_ptr`` 布局（输入、第二操作数、输出地址与
    各元素数，各 NT 项，int64），grid 同样按 ``(tensor, part)`` 线性展开
    且恒为 ``NT * PARTS``，覆盖洞按构造不存在。``EXACT`` 在每个元素数
    都整除 ``BLOCK`` 时去掉逐 tile 边界 mask（免 mask 双臂判例沿
    maximum_List / addcdiv__Scalar 家族先例）；不整除的 ragged 形态
    走 masked 臂，语义不变。
    """
    pid = tl.program_id(0)
    tensor_id = pid % NT
    part_id = pid // NT

    a_ptr = tl.load(meta_ptr + tensor_id).to(tl.pointer_type(A_DT))
    b_ptr = tl.load(meta_ptr + NT + tensor_id).to(tl.pointer_type(A_DT))
    out_ptr = tl.load(meta_ptr + 2 * NT + tensor_id).to(tl.pointer_type(A_DT))
    n_elements = tl.load(meta_ptr + 3 * NT + tensor_id)

    arange = tl.arange(0, BLOCK)
    # tile 计数保持 i32，与公共执行器的地址算术宽度一致。
    num_tiles = tl.cdiv(n_elements, BLOCK).to(tl.int32)
    if EXACT:
        for block_id in tl.range(part_id, num_tiles, PARTS):
            idx = block_id * BLOCK + arange
            a = tl.load(a_ptr + idx)
            b = tl.load(b_ptr + idx)
            tl.store(out_ptr + idx, fn(a, b).to(A_DT))
    else:
        for block_id in tl.range(part_id, num_tiles, PARTS):
            idx = block_id * BLOCK + arange
            mask = idx < n_elements
            a = tl.load(a_ptr + idx, mask=mask, other=0)
            b = tl.load(b_ptr + idx, mask=mask, other=0)
            tl.store(out_ptr + idx, fn(a, b).to(A_DT), mask=mask)


def _run_pow_list_cached(self, other):
    """均匀浮点配对列表的单 launch in-place 路径（metadata 只读缓存）。

    广播 ``.List``（第二操作数与对应输入元素数不同）不与输入共用平坦
    索引，跨设备或超 grid 上限的形态同样返回 ``FALLBACK``，由调用方
    决定回退目标；metadata 只含地址与元素数，kernel 每次仍完整读取并
    计算张量数据，缓存仅省去重复的同步 H2D。
    """
    if not can_use_flat(self, other, MODE_LIST):
        return FALLBACK
    if not all(
        other_tensor.numel() == tensor.numel()
        for tensor, other_tensor in zip(self, other)
    ):
        return FALLBACK
    num_tensors = len(self)
    if num_tensors * FAST_PARTS_CAP > _MAX_GRID_X:
        return FALLBACK
    device = self[0].device
    for tensor, other_tensor in zip(self, other):
        if tensor.device != device or other_tensor.device != device:
            return FALLBACK

    in_ptrs = [tensor.data_ptr() for tensor in self]
    b_ptrs = [tensor.data_ptr() for tensor in other]
    numels = [tensor.numel() for tensor in self]
    meta = _device_meta(in_ptrs + b_ptrs + in_ptrs + numels, device)
    parts = max(1, min(FAST_PARTS_CAP, triton.cdiv(max(numels), FAST_BLOCK)))
    fused_pow_list_ip_kernel[(num_tensors * parts,)](
        meta,
        _pow_fn,
        num_tensors,
        _TL_DTYPES[self[0].dtype],
        FAST_BLOCK,
        parts,
        num_warps=FAST_WARPS,
        num_stages=FAST_STAGES,
    )
    return None


def _foreach_pow__List(self, other):
    logger.debug("GEMS_GCU400 _FOREACH_POW__LIST")

    def fallback():
        return _apply_list("pow", self, other, inplace=True)

    if FALLBACK_TO_PUBLIC:
        return fallback()
    result = _run_pow_list_cached(self, other)
    if result is not FALLBACK:
        # in-place schema contract: the dispatcher must return None.
        return None
    result = run_binary(
        self,
        other,
        OP_POW,
        MODE_LIST,
        True,
        fixed_grid=FIXED_GRID,
        block_size=BLOCK_SIZE,
        num_warps=NUM_WARPS,
        num_stages=NUM_STAGES,
        use_device_context=USE_DEVICE_CONTEXT,
        fp32_promote=FP32_PROMOTE,
        fused=FUSED_LAUNCH,
    )
    if result is FALLBACK:
        return fallback()
    return result


def _run_pow_list_oop(self, other):
    """均匀浮点配对列表的单 launch out-of-place 路径。

    输出张量按 ATen 语义逐个 ``torch.empty_like`` 分配（每次调用的地址
    不同，metadata 缓存天然 miss，与共享 flat 路径的 H2D 行为一致）。
    广播 ``.List``、跨设备、非连续/非浮点与超 grid 上限形态返回
    ``FALLBACK``，由调用方交给共享执行器，dtype policy 与异常语义不变。
    """
    if not can_use_flat(self, other, MODE_LIST):
        return FALLBACK
    if not all(
        other_tensor.numel() == tensor.numel()
        for tensor, other_tensor in zip(self, other)
    ):
        return FALLBACK
    num_tensors = len(self)
    if num_tensors * OOP_PARTS_CAP > _MAX_GRID_X:
        return FALLBACK
    device = self[0].device
    for tensor, other_tensor in zip(self, other):
        if tensor.device != device or other_tensor.device != device:
            return FALLBACK

    outputs = [torch.empty_like(tensor) for tensor in self]
    a_ptrs = [tensor.data_ptr() for tensor in self]
    b_ptrs = [tensor.data_ptr() for tensor in other]
    out_ptrs = [tensor.data_ptr() for tensor in outputs]
    numels = [tensor.numel() for tensor in self]
    meta = _device_meta(a_ptrs + b_ptrs + out_ptrs + numels, device)
    parts = max(1, min(OOP_PARTS_CAP, triton.cdiv(max(numels), OOP_BLOCK)))
    exact = int(all(numel % OOP_BLOCK == 0 for numel in numels))
    fused_pow_list_kernel[(num_tensors * parts,)](
        meta,
        _pow_fn,
        num_tensors,
        _TL_DTYPES[self[0].dtype],
        exact,
        OOP_BLOCK,
        parts,
        num_warps=OOP_WARPS,
        num_stages=OOP_STAGES,
    )
    return outputs


def _foreach_pow_List(self, other):
    logger.debug("GEMS_GCU400 _FOREACH_POW_LIST")

    results = _run_pow_list_oop(self, other)
    if results is not FALLBACK:
        return results
    if can_use_flat(self, other, MODE_LIST) and not all(
        other_tensor.numel() == tensor.numel()
        for tensor, other_tensor in zip(self, other)
    ):
        # 广播 ``.List``（第二操作数含 1 元素张量）：共享 flat 路径与公共
        # 执行器都按 paired 平坦索引读第二列表，对 1 元素分配是越界读
        # （实测输出含垃圾值，native aten / CPU 参考均广播语义）。改走
        # in-place 路径同款的逐 tensor 广播层（三 dtype 与 native 对齐，
        # 0 维与 (1,) 第二操作数均覆盖）。
        result = run_binary(
            self,
            other,
            OP_POW,
            MODE_LIST,
            False,
            fixed_grid=FIXED_GRID,
            block_size=BLOCK_SIZE,
            num_warps=NUM_WARPS,
            num_stages=NUM_STAGES,
            use_device_context=USE_DEVICE_CONTEXT,
            fp32_promote=FP32_PROMOTE,
            fused=FUSED_LAUNCH,
        )
        if result is not FALLBACK:
            return result
    # 共享 ``_foreach_binary`` 执行器 = 既有生产路径：家族 flat kernel 先行，
    # 异常形态回退公共执行器，bool 拒绝 / dtype 提升 / 长度校验逐字不变。
    return _apply_list_local("pow", self, other, inplace=False)
