# Small-T cutoff: with at most this many time steps the whole metadata
# (batch_sizes + prefix offsets) travels inside the kernel launch packet as
# packed int64 scalars, which avoids the CPU->GCU copy entirely. A pageable
# H2D copy on this stack stalls the device pipeline behind whatever is in
# flight (in kernel-mode benchmarks: the 256 MB L2 flush), exposing ~50 us
# that a tiny copy cannot hide; the aten composite native baseline reads
# batch_sizes on the host and pays no H2D at all.
_SMALL_T_MAX = 32

# do_not_specialize on every runtime int: value classes (==1, %16) would
# multiply kernel variants across shapes/dtypes for zero benefit here, and
# the small-T arm's 32 packed metadata scalars must never be specialized.
_DNS = [
    "num_items",
    "num_steps",
    "b_tiles",
    "max_batch",
    "feature_size",
    "out_stride_t",
    "out_stride_b",
]
_DNS_SMALL = _DNS + [f"p{i}" for i in range(_SMALL_T_MAX)]


@triton.jit
def _pps_copy_tile(
    data,
    output,
    padding_value,
    src_base,
    out_base,
    active,
    b_mask,
    feature_size,
    chunk,
    BLOCK_F: tl.constexpr,
):
    cols = chunk + tl.arange(0, BLOCK_F)
    col_mask = cols < feature_size
    load_mask = active[:, None] & col_mask[None, :]
    # Masked load without `other=` (garbage on inactive lanes is discarded by
    # the where below): `other=` on wide masked tiles is a known miscode /
    # load-merging hazard on this backend.
    vals = tl.load(data + (src_base[:, None] + cols[None, :]), mask=load_mask)
    vals = tl.where(active[:, None], vals, padding_value.to(vals.dtype))
    store_mask = b_mask[:, None] & col_mask[None, :]
    tl.store(output + (out_base[:, None] + cols[None, :]), vals, mask=store_mask)


