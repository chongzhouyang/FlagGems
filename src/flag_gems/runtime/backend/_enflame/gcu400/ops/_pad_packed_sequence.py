def _pick_launch(feature_size, max_batch, elem_size):
    """Tile shape / num_warps selection (kept hookable for tuning).

    Tile lanes cap at 8192 (the masked-tile miscode safe domain on this
    backend, verified live: 16384-lane variants silently return wrong
    data); 8-byte elements halve it for DSM headroom. Measured on gcu400,
    the largest legal B_TILE wins at every feature width because the
    t-major work item streams one contiguous run per side.
    """
    block_f = min(triton.next_power_of_2(max(feature_size, 1)), 1024)
    f_tiles = triton.cdiv(max(feature_size, 1), block_f)
    if not 1 <= f_tiles <= 8:
        f_tiles = 0
    lanes_cap = 4096 if elem_size >= 8 else 8192
    b_tile_cap = max(1, lanes_cap // block_f)
    b_tile = min(triton.next_power_of_2(max(max_batch, 1)), b_tile_cap)
    num_warps = 4 if b_tile * block_f >= 2048 else 2
    return b_tile, block_f, f_tiles, num_warps


def _pad_packed_sequence(data, batch_sizes, batch_first, padding_value, total_length):
    """Pad a packed variable-length sequence back into a dense tensor.

    Inverse of ``_pack_padded_sequence``: scatters ``data`` (shape
    ``(sum(batch_sizes), *)``) into a padded ``(T, B, *)`` tensor (or
    ``(B, T, *)`` when ``batch_first``) and returns it together with the
    per-batch-element sequence lengths.

    Args:
        data: packed values tensor.
        batch_sizes: 1D CPU int64 tensor of active counts per time step.
        batch_first: if True, output layout is (B, T, *) instead of (T, B, *).
        padding_value: value used for padded positions.
        total_length: pad the time dimension out to at least this many steps;
            values <= 0 mean use the number of steps in ``batch_sizes``.

    Returns:
        Tuple of (padded output tensor, lengths tensor).
    """
    logger.debug("GEMS_ENFLAME _PAD_PACKED_SEQUENCE")

    num_steps = batch_sizes.numel()
    max_batch = int(batch_sizes[0].item())

    total_steps = num_steps
    if total_length > 0:
        total_steps = max(total_steps, int(total_length))

    # batch_sizes is a small CPU int64 tensor (aten contract). All metadata
    # math (exclusive prefix sum, per-element lengths) stays on the host in
    # numpy so no aten compute op runs on the op path.
    if (
        batch_sizes.device.type == "cpu"
        and batch_sizes.dtype == torch.int64
        and batch_sizes.is_contiguous()
    ):
        bs_np = batch_sizes.numpy()
    else:
        bs_np = (
            batch_sizes.detach()
            .to(device="cpu", dtype=torch.int64)
            .contiguous()
            .numpy()
        )

    offsets_np = np.zeros(num_steps, dtype=np.int64)
    if num_steps > 1:
        np.cumsum(bs_np[:-1], out=offsets_np[1:])
    lengths_np = np.searchsorted(bs_np[::-1], np.arange(max_batch), side="right")
    lengths_np = (num_steps - lengths_np).astype(np.int64, copy=False)
    lengths = torch.from_numpy(lengths_np)

    feature_shape = data.shape[1:]
    feature_size = 1
    for size in feature_shape:
        feature_size *= size
    if not data.is_contiguous():
        data = data.contiguous()

    num_rows = total_steps * max_batch
    # int32 element offsets are only safe while every row offset stays below
    # 2**31; beyond that the main arm switches to int64 index math (WIDE).
    wide = num_rows * feature_size > 2**31 - 2**24 or data.numel() > 2**31 - 2**24

    # Order matters for the measured timeline: everything below except the
    # H2D copy and the launch is pure host work that overlaps whatever the
    # device is still busy with, so it stays off the clock. The copy (when
    # present) and the launch go last.
    b_tile, block_f, f_tiles, num_warps = _pick_launch(
        feature_size, max_batch, data.element_size()
    )
    b_tiles = triton.cdiv(max_batch, b_tile)
    num_items = total_steps * b_tiles
    grid = (min(num_items, MAX_GRID_DIM),)

    # batch_first is handled purely by output strides: the kernel writes
    # rows at t*out_stride_t + b*out_stride_b, so no transpose+contiguous
    # copy is needed for either layout.
    if batch_first:
        output = torch.empty(
            (max_batch, total_steps, *feature_shape),
            dtype=data.dtype,
            device=data.device,
        )
        out_flat = output.view(max_batch, total_steps, feature_size)
        out_stride_t = out_flat.stride(1)
        out_stride_b = out_flat.stride(0)
    else:
        output = torch.empty(
            (total_steps, max_batch, *feature_shape),
            dtype=data.dtype,
            device=data.device,
        )
        out_flat = output.view(total_steps, max_batch, feature_size)
        out_stride_t = out_flat.stride(0)
        out_stride_b = out_flat.stride(1)

    if num_rows > 0:
        if num_steps <= _SMALL_T_MAX and not wide:
            # Launch-packet metadata arm: no H2D copy at all.
            bs_list = bs_np.tolist()
            offs_list = offsets_np.tolist()
            packed = [((off + 1) << 32) | bs for bs, off in zip(bs_list, offs_list)]
            packed += [0] * (_SMALL_T_MAX - num_steps)
            _pad_packed_sequence_kernel_small[grid](
                data,
                out_flat,
                padding_value,
                num_items,
                num_steps,
                b_tiles,
                max_batch,
                feature_size,
                out_stride_t,
                out_stride_b,
                *packed,
                B_TILE=b_tile,
                BLOCK_F=block_f,
                F_TILES=f_tiles,
                num_warps=num_warps,
            )
        else:
            # The two device-side metadata vectors travel in one H2D copy.
            meta_dtype = np.int64 if wide else np.int32
            meta_np = np.empty(2 * num_steps, dtype=meta_dtype)
            meta_np[:num_steps] = bs_np
            meta_np[num_steps:] = offsets_np
            metadata_dev = torch.from_numpy(meta_np).to(data.device)
            _pad_packed_sequence_kernel[grid](
                data,
                metadata_dev[:num_steps],
                metadata_dev[num_steps:],
                out_flat,
                padding_value,
                num_items,
                num_steps,
                b_tiles,
                max_batch,
                feature_size,
                out_stride_t,
                out_stride_b,
                B_TILE=b_tile,
                BLOCK_F=block_f,
                F_TILES=f_tiles,
                WIDE=wide,
                num_warps=num_warps,
            )

    return output, lengths
