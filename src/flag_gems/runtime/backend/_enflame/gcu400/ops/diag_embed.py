"""GCU400 专属 ``diag_embed``：按输出形态分档的 Triton 路径。

公共实现先用 ``torch.zeros`` 清零整块输出，再用 ``pointwise_dynamic``
生成的 kernel 向 ``torch.diagonal`` 得到的非连续 view 写对角线；后者在
GCU 上会被多维索引分解拖慢，小 shape 还要多付一次 launch。

* 对角轴为输出最后两维（归一化后 dim1=rank-2、dim2=rank-1，任意 offset）：
  单次 launch 的持久化两阶段 kernel 一次写满输出——每 program 认领连续
  chunk run，先把整段输出按 int 视图向量化零填充，``tl.debug_barrier``
  后按对角平坦索引 masked 散写落在本 run 内的对角元。对角元的定位只需
  每元一次 i32 除法 + i64 仿射地址，没有逐元素 where/select 机构税
  （diagflat 家族定标：2D tile 逐元素 compare/select 比平坦 fill 慢
  1.6-1.9 倍）。输出 ≤ ``FUSED_MAX_ELEMENTS`` 走此路径；更大的输出
  fill 与 scatter 串行段变长，退回 ``torch.zeros`` + 散写双 launch。
* 其余维度组合：小输出走单 kernel 坐标分解一次写满；大输出保留
  ``torch.zeros`` 的高效整块清零，再按输入平坦索引散写对角线，
  避免逐元素分解整个输出（大输出上整数除法代价远超收益）。
"""

"""GCU400-specific ``diag_embed``: two Triton paths tiered by output size.

The common implementation first zeros the whole output with ``torch.zeros``, then uses a kernel generated by
``pointwise_dynamic`` to write the diagonal into the non-contiguous view from ``torch.diagonal``; the latter is
slowed by multi-dimensional index decomposition on GCU, and small shapes pay an extra launch.

* Small output: ``torch.empty`` + a single 1D flat kernel fills the whole output in one pass, taking
  input values on the diagonal and writing 0 elsewhere, removing the zeroing launch and codegen's multi-dim
  decomposition.
* Large output: keep ``torch.zeros`` for efficient bulk zeroing and replace only the diagonal copy with a 1D kernel that
  reads contiguously by input flat index and scatters by diagonal stride, avoiding per-element decomposition of the
  whole
  output (integer division costs far more than it saves on large outputs).
"""

import logging  # noqa: E402
from contextlib import nullcontext  # noqa: E402

import torch  # noqa: E402
import triton  # noqa: E402
import triton.language as tl  # noqa: E402

from flag_gems.runtime import torch_device_fn  # noqa: E402
from flag_gems.utils import libentry  # noqa: E402

from ..utils.pointwise_dynamic import pointwise_dynamic  # noqa: E402

logger = logging.getLogger(__name__)

# --- TUNING PARAMS START ---
# Generated per optimization round; all compile-time / launch-time config, semantics unchanged.
FIXED_GRID = 48
BLOCK_SIZE = 8192
NUM_WARPS = 4
NUM_STAGES = 1
USE_DEVICE_CONTEXT = 1
FALLBACK_TO_ORIGINAL = 0
# When the number of output elements exceeds this threshold, take the zeros + diagonal scatter path:
# Per-element coordinate decomposition in a single kernel gets bogged down by integer division on large outputs.
SMALL_OUTPUT_LIMIT = 2097152
# Whether the large-output path uses a hand-written scatter kernel instead of pointwise_dynamic codegen.
LARGE_USE_SCATTER = 1
SCATTER_BLOCK_SIZE = 8192
SCATTER_NUM_WARPS = 4
# The scatter kernel uses int64 addresses and can cover outputs with more than 2^30 elements; keep the upper limit
# as a safeguard for extreme scales; normal cases will not hit it.
SCATTER_INDEX_LIMIT = 1 << 40
# Persistent fused path (last two dimensions are the diagonal axes): number of zero-filled tile bytes per program
# and the program count (diagflat tuning: 24 persistent programs beat 48 and non-multiples of 24).
FUSED_TILE_BYTES = 131072
FUSED_PROGS = 24
FUSED_SPAN_CAP = 4096
# Output element cap for the fused path: for larger outputs the fill+scatter serial section gets longer,
# so the two-launch zeros+scatter is faster instead (measured and tuned at (1024,1024)).
FUSED_MAX_ELEMENTS = 64 * 1024 * 1024
# --- TUNING PARAMS END ---

# The kernel unrolls coordinate decomposition for a fixed 4 dimensions; when the actual rank is less than 4, extra
# dimensions are filled with size=1.
_MAX_RANK = 4


@pointwise_dynamic(is_tensor=[True], promotion_methods=[(0, "DEFAULT")])
@triton.jit
def _diagonal_copy_func(inp):
    """Diagonal-view copy of the original path; created once at module level to reuse the compile cache."""
    return inp


@libentry()
@triton.jit(do_not_specialize=["TOTAL"])
def _diag_embed_fill_kernel(
    x_ptr,
    y_ptr,
    TOTAL,
    Y_STRIDE_0: tl.constexpr,
    Y_STRIDE_1: tl.constexpr,
    Y_STRIDE_2: tl.constexpr,
    Y_STRIDE_3: tl.constexpr,
    Y_SIZE_0: tl.constexpr,
    Y_SIZE_1: tl.constexpr,
    Y_SIZE_2: tl.constexpr,
    Y_SIZE_3: tl.constexpr,
    X_COEFF_0: tl.constexpr,
    X_COEFF_1: tl.constexpr,
    X_COEFF_2: tl.constexpr,
    X_COEFF_3: tl.constexpr,
    DIM1: tl.constexpr,
    DIM2: tl.constexpr,
    OFFSET: tl.constexpr,
    BLOCK: tl.constexpr,
    GRID: tl.constexpr,
):
    """Fixed grid + in-kernel striding that fills the whole output with diagonal and zero values in one pass."""
    arange = tl.arange(0, BLOCK)
    pid = tl.program_id(0)
    num_programs = tl.num_programs(0)
    for block_id in tl.range(pid, tl.cdiv(TOTAL, BLOCK), num_programs):
        output_index = block_id * BLOCK + arange
        valid = output_index < TOTAL
        # The output is a contiguous tensor, so inverting coordinates dimension by dimension gives the positions of the
        # two diagonal axes.
        coord_0 = (output_index // Y_STRIDE_0) % Y_SIZE_0
        coord_1 = (output_index // Y_STRIDE_1) % Y_SIZE_1
        coord_2 = (output_index // Y_STRIDE_2) % Y_SIZE_2
        coord_3 = (output_index // Y_STRIDE_3) % Y_SIZE_3
        if DIM1 == 0:
            diag_coord_1 = coord_0
        elif DIM1 == 1:
            diag_coord_1 = coord_1
        elif DIM1 == 2:
            diag_coord_1 = coord_2
        else:
            diag_coord_1 = coord_3
        if DIM2 == 0:
            diag_coord_2 = coord_0
        elif DIM2 == 1:
            diag_coord_2 = coord_1
        elif DIM2 == 2:
            diag_coord_2 = coord_2
        else:
            diag_coord_2 = coord_3
        # With offset>0 the diagonal index comes from the dim1 coordinate, with offset<0 from the dim2 coordinate,
        # both unified to the smaller value; an element is a valid diagonal element only when the two axis coordinates
        # differ by exactly offset.
        on_diagonal = (diag_coord_2 - diag_coord_1 == OFFSET) & valid
        diagonal_index = tl.minimum(diag_coord_1, diag_coord_2)
        input_index = (
            coord_0 * X_COEFF_0
            + coord_1 * X_COEFF_1
            + coord_2 * X_COEFF_2
            + coord_3 * X_COEFF_3
            + diagonal_index
        )
        value = tl.load(x_ptr + input_index, mask=on_diagonal, other=0)
        tl.store(y_ptr + output_index, value, mask=valid)


@libentry()
@triton.jit(do_not_specialize=["TOTAL"])
def _diag_embed_scatter_kernel(
    x_ptr,
    y_ptr,
    TOTAL,
    N: tl.constexpr,
    DIAG_STRIDE: tl.constexpr,
    OFFSET_TERM: tl.constexpr,
    OUTER_SIZE_0: tl.constexpr,
    OUTER_SIZE_1: tl.constexpr,
    OUTER_Y_STRIDE_0: tl.constexpr,
    OUTER_Y_STRIDE_1: tl.constexpr,
    NUM_OUTER_AXES: tl.constexpr,
    BLOCK: tl.constexpr,
    GRID: tl.constexpr,
):
    """Read contiguously by input flat index and scatter to the zeroed output by diagonal stride."""
    arange = tl.arange(0, BLOCK)
    pid = tl.program_id(0)
    num_programs = tl.num_programs(0)
    for block_id in tl.range(pid, tl.cdiv(TOTAL, BLOCK), num_programs):
        input_index = block_id * BLOCK + arange
        valid = input_index < TOTAL
        # x is stored contiguously as [outer..., N]; its last dimension is the diagonal index.
        diagonal_index = input_index % N
        outer_index = input_index // N
        if NUM_OUTER_AXES == 1:
            outer_coord_0 = outer_index % OUTER_SIZE_0
            outer_coord_1 = 0
        else:
            outer_coord_0 = outer_index // OUTER_SIZE_1
            outer_coord_1 = outer_index % OUTER_SIZE_1
        # Each diagonal step advances both dim1 and dim2 coordinates by 1; offset only contributes a constant term.
        # The output may exceed 2^30 elements, so addresses must be int64 or GCU truncates the high bits.
        output_index = (
            outer_coord_0.to(tl.int64) * OUTER_Y_STRIDE_0
            + outer_coord_1.to(tl.int64) * OUTER_Y_STRIDE_1
            + diagonal_index.to(tl.int64) * DIAG_STRIDE
            + OFFSET_TERM
        )
        value = tl.load(x_ptr + input_index, mask=valid)
        tl.store(y_ptr + output_index, value, mask=valid)


@libentry()
@triton.jit(
    do_not_specialize=["count", "m", "m2", "n", "base_term", "ndiag", "chunks", "cpb"]
)
def _diag_embed_fused_kernel(
    fill_ptr,
    out_ptr,
    src_ptr,
    count,
    m,
    m2,
    n,
    base_term,
    ndiag,
    chunks,
    cpb,
    RATIO: tl.constexpr,
    BLOCK: tl.constexpr,
    SPAN: tl.constexpr,
):
    """持久化两阶段：向量化零填充整段 run，一次 barrier 后写本 run 的对角元。

    输出按 ``RATIO`` 个元素一道的 int 视图零填充（fill_ptr），对角元按
    原生 dtype 散写（out_ptr）。program ``pid`` 认领连续 chunk run
    ``[pid * cpb, min(pid * cpb + cpb, chunks))``，run 之间地址不相交，
    因此零与对角值只在本 program 内竞争：``tl.debug_barrier`` 保证本 run
    的零先于对角值落盘。

    对角元 ``i``（x 平坦索引，``i = outer * n + rr``）的输出地址为
    ``outer * m2 + rr * (m + 1) + base_term``，其中
    ``base_term = max(-offset, 0) * (m + 1) + offset`` 把 offset 的两种
    符号统一成常数项。地址随 ``i`` 单调不减，run 首尾用一次标量除法
    求出 ``[first, last)`` 索引窗，窗内逐 SPAN 步进；越窗边界（跨 outer
    段）由 ``addr < hi`` 掩码过滤，两端相邻 run 重叠写的对角元取值恒等，
    重复写入无害。
    """
    pid = tl.program_id(0)
    start = pid * cpb
    end = tl.minimum(start + cpb, chunks)
    zero = tl.zeros([BLOCK], dtype=fill_ptr.dtype.element_ty)
    for chunk in range(start, end):
        base = chunk * BLOCK
        offsets = base + tl.arange(0, BLOCK)
        if base + BLOCK <= count:
            tl.store(fill_ptr + offsets, zero)
        else:
            tl.store(fill_ptr + offsets, zero, mask=offsets < count)
    tl.debug_barrier()
    if ndiag > 0:
        lo = start.to(tl.int64) * BLOCK * RATIO
        hi = end.to(tl.int64) * BLOCK * RATIO
        first = ((lo // m2) * n).to(tl.int32)
        last = tl.minimum(ndiag, ((hi + m2 - 1) // m2) * n).to(tl.int32)
        if last > first:
            for head in range(first, last, SPAN):
                idx = head + tl.arange(0, SPAN)
                outer = idx // n
                diag = idx - outer * n
                addr = outer.to(tl.int64) * m2 + diag.to(tl.int64) * (m + 1) + base_term
                valid = (idx < last) & (addr < hi)
                value = tl.load(
                    src_ptr + idx,
                    mask=valid,
                    other=tl.zeros([SPAN], dtype=src_ptr.dtype.element_ty),
                )
                tl.store(out_ptr + addr, value, mask=valid)


_FILL_VIEWS = {
    1: torch.uint8,
    2: torch.int16,
    4: torch.int32,
    8: torch.int64,
}


def _fused_fill_ratio(itemsize, last_dim):
    """零填充视图的加宽倍数：bool 尽量按 4 字节一道写入，其余按原生宽度。

    torch.zeros 的 bool 填充带宽只有宽道填充的一半左右（1GiB 实测 438µs
    vs 348µs），Triton 里把 4 个 bool 打包成 int32 一道写可贴满写带宽；
    2/4 字节 dtype 原生道宽已能贴满地板，无需加宽。视图要求最后一维可
    被倍数整除，不满足时逐级降档。
    """
    if itemsize != 1:
        return 1
    for ratio in (4, 2, 1):
        if last_dim % ratio == 0:
            return ratio
    return 1


def _diag_embed_fused(x, y_shape, m, n, offset):
    """对角轴为输出最后两维的连续场景：单 launch 持久化写满输出。"""
    if not x.is_contiguous():
        x = x.contiguous()
    y = torch.empty(y_shape, dtype=x.dtype, device=x.device)
    y_count = y.numel()
    ratio = _fused_fill_ratio(y.element_size(), m)
    view_dtype = _FILL_VIEWS[y.element_size() * ratio]
    view_count = y_count // ratio
    block = min(
        max(16, FUSED_TILE_BYTES // (y.element_size() * ratio)),
        triton.next_power_of_2(max(16, view_count // FUSED_PROGS)),
    )
    chunks = triton.cdiv(view_count, block)
    nprog = min(FUSED_PROGS, chunks)
    cpb = triton.cdiv(chunks, nprog)
    diag_in_run = (cpb * block * ratio) // (m + 1) + 2
    span = min(FUSED_SPAN_CAP, max(16, triton.next_power_of_2(diag_in_run)))
    base_term = max(-offset, 0) * (m + 1) + offset
    device_context = (
        torch_device_fn.device(x.device) if USE_DEVICE_CONTEXT else nullcontext()
    )
    with device_context:
        _diag_embed_fused_kernel[(nprog,)](
            y.view(view_dtype),
            y,
            x,
            view_count,
            m,
            m * m,
            n,
            base_term,
            x.numel(),
            chunks,
            cpb,
            RATIO=ratio,
            BLOCK=block,
            SPAN=span,
            num_warps=NUM_WARPS,
        )
    return y


def _diag_embed_original(x, offset, dim1, dim2, y_shape):
    """原始 zeros + diagonal-view 路径，用于超出平坦索引上限或强制对照。"""
    y = torch.zeros(y_shape, dtype=x.dtype, device=x.device)
    diagonal_view = torch.diagonal(y, offset, dim1, dim2)
    _diagonal_copy_func.instantiate(x.ndim)(x, out0=diagonal_view)
    return y


def _diag_embed_large(x, offset, dim1, dim2, y_shape, diagonal_length, y_strides):
    """Large output: bulk zeros clearing + a 1D scatter kernel writing the diagonal."""
    if not LARGE_USE_SCATTER:
        y = torch.zeros(y_shape, dtype=x.dtype, device=x.device)
        diagonal_view = torch.diagonal(y, offset, dim1, dim2)
        _diagonal_copy_func.instantiate(x.ndim)(x, out0=diagonal_view)
        return y

    if not x.is_contiguous():
        x = x.contiguous()

    rank = len(y_shape)
    outer_axes = [axis for axis in range(rank) if axis not in (dim1, dim2)]
    outer_sizes = [y_shape[axis] for axis in outer_axes]
    # Input outer dimensions are expanded by contiguous layout; at most two outer axes (rank <= 4).
    outer_size_0 = outer_sizes[0] if len(outer_sizes) >= 1 else 1
    outer_size_1 = outer_sizes[1] if len(outer_sizes) >= 2 else 1
    outer_y_stride_0 = y_strides[outer_axes[0]] if len(outer_axes) >= 1 else 0
    outer_y_stride_1 = y_strides[outer_axes[1]] if len(outer_axes) >= 2 else 0

    diag_stride = y_strides[dim1] + y_strides[dim2]
    # With offset>0 the dim2 coordinate gains offset, with offset<0 the dim1 coordinate gains -offset.
    offset_term = max(offset, 0) * y_strides[dim2] + max(-offset, 0) * y_strides[dim1]

    y = torch.zeros(y_shape, dtype=x.dtype, device=x.device)
    total_input_elements = x.numel()
    grid = (min(triton.cdiv(total_input_elements, SCATTER_BLOCK_SIZE), FIXED_GRID),)
    device_context = (
        torch_device_fn.device(x.device) if USE_DEVICE_CONTEXT else nullcontext()
    )
    with device_context:
        _diag_embed_scatter_kernel[grid](
            x,
            y,
            total_input_elements,
            N=diagonal_length,
            DIAG_STRIDE=diag_stride,
            OFFSET_TERM=offset_term,
            OUTER_SIZE_0=outer_size_0,
            OUTER_SIZE_1=outer_size_1,
            OUTER_Y_STRIDE_0=outer_y_stride_0,
            OUTER_Y_STRIDE_1=outer_y_stride_1,
            NUM_OUTER_AXES=len(outer_axes),
            BLOCK=SCATTER_BLOCK_SIZE,
            GRID=FIXED_GRID,
            num_warps=SCATTER_NUM_WARPS,
        )
    return y


def diag_embed(x, offset=0, dim1=-2, dim2=-1):
    logger.debug("GEMS_GCU400 DIAG_EMBED")

    rank = x.ndim + 1
    assert dim1 >= -rank and dim1 < rank, f"Invalid dim1: {dim1}"
    assert dim2 >= -rank and dim2 < rank, f"Invalid dim2: {dim2}"
    dim1 = dim1 % rank
    dim2 = dim2 % rank
    assert dim1 != dim2, "diagonal dimensions cannot be identical"

    # Swapping the two diagonal axes is equivalent to negating offset, so normalize to dim1 < dim2 first.
    if dim1 > dim2:
        offset = -offset
        dim1, dim2 = dim2, dim1

    diagonal_length = x.size(-1)
    last_dim = diagonal_length + abs(offset)
    y_shape = list(x.shape)
    y_shape.pop()
    y_shape.insert(dim1, last_dim)
    y_shape.insert(dim2, last_dim)

    total_elements = 1
    for dimension in y_shape:
        total_elements *= dimension

    if FALLBACK_TO_ORIGINAL or rank > _MAX_RANK:
        return _diag_embed_original(x, offset, dim1, dim2, y_shape)
    # When the diagonal axes are exactly the last two output dimensions (any offset), use a single-launch persistent
    # kernel
    # to fill the output in one go: zero-fill + scatter of this run's diagonal elements, with no per-element
    # where/select
    # fixed overhead, and no second launch for zeros.
    if dim1 == rank - 2 and dim2 == rank - 1 and total_elements <= FUSED_MAX_ELEMENTS:
        if x.numel() == 0:
            return torch.zeros(y_shape, dtype=x.dtype, device=x.device)
        return _diag_embed_fused(x, y_shape, last_dim, diagonal_length, offset)

    # y is stored in a contiguous layout, and each dimension's stride is derived from the suffix product of the shape.
    y_strides = [1] * rank
    for axis in range(rank - 2, -1, -1):
        y_strides[axis] = y_strides[axis + 1] * y_shape[axis + 1]

    if total_elements > SMALL_OUTPUT_LIMIT:
        if total_elements > SCATTER_INDEX_LIMIT:
            return _diag_embed_original(x, offset, dim1, dim2, y_shape)
        return _diag_embed_large(
            x, offset, dim1, dim2, y_shape, diagonal_length, y_strides
        )

    if not x.is_contiguous():
        x = x.contiguous()

    # x's dimension order is "all y dimensions except the two diagonal axes" followed by the last dimension,
    # so each y axis coordinate's coefficient in x's flat index is the product of all following x dimension lengths.
    outer_axes = [axis for axis in range(rank) if axis not in (dim1, dim2)]
    outer_sizes = [y_shape[axis] for axis in outer_axes] + [diagonal_length]
    x_coeffs = [0] * rank
    for position, axis in enumerate(outer_axes):
        coefficient = 1
        for size in outer_sizes[position + 1 :]:
            coefficient *= size
        x_coeffs[axis] = coefficient

    pad_count = _MAX_RANK - rank
    y_strides += [1] * pad_count
    y_sizes = list(y_shape) + [1] * pad_count
    x_coeffs += [0] * pad_count

    y = torch.empty(y_shape, dtype=x.dtype, device=x.device)
    grid = (min(triton.cdiv(total_elements, BLOCK_SIZE), FIXED_GRID),)
    device_context = (
        torch_device_fn.device(x.device) if USE_DEVICE_CONTEXT else nullcontext()
    )
    with device_context:
        _diag_embed_fill_kernel[grid](
            x,
            y,
            total_elements,
            Y_STRIDE_0=y_strides[0],
            Y_STRIDE_1=y_strides[1],
            Y_STRIDE_2=y_strides[2],
            Y_STRIDE_3=y_strides[3],
            Y_SIZE_0=y_sizes[0],
            Y_SIZE_1=y_sizes[1],
            Y_SIZE_2=y_sizes[2],
            Y_SIZE_3=y_sizes[3],
            X_COEFF_0=x_coeffs[0],
            X_COEFF_1=x_coeffs[1],
            X_COEFF_2=x_coeffs[2],
            X_COEFF_3=x_coeffs[3],
            DIM1=dim1,
            DIM2=dim2,
            OFFSET=offset,
            BLOCK=BLOCK_SIZE,
            GRID=FIXED_GRID,
            num_warps=NUM_WARPS,
            num_stages=NUM_STAGES,
        )
    return y
