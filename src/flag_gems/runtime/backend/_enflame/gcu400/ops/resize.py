_SMALL_N = 1 << 14  # n <= 16K elements: single-wave tiny copies
_SMALL_TILE = 4096
_TILE_BYTES_BIG = 256 * 1024  # streaming regime: 256 KiB per tile
_BIG_BYTES_16BIT = 256 * 1024 * 1024  # 16-bit switches to widened path at >= 256 MiB
_MED_TILE_16BIT = 16384  # 32 KiB per tile for 16-bit medium sizes
_FIXED_CTAS = 48  # enflame codegen max_grid_size[0]
_NUM_WARPS = 4  # enflame codegen max_num_warps_per_cta


@triton.jit
def _resize_copy_kernel(
    src_ptr,
    dst_ptr,
    n_elements,
    tiles_per_cta,
    num_tiles,
    TILE_SIZE: tl.constexpr,
    EVEN: tl.constexpr,
    IDX64: tl.constexpr,
):
    pid = tl.program_id(axis=0)
    num_ctas = tl.num_programs(axis=0)
    for j in range(0, tiles_per_cta):
        tile_id = pid + j * num_ctas
        if IDX64:
            offs = tile_id.to(tl.int64) * TILE_SIZE + tl.arange(0, TILE_SIZE)
        else:
            offs = tile_id * TILE_SIZE + tl.arange(0, TILE_SIZE)
        if EVEN:
            if tile_id < num_tiles:
                vals = tl.load(src_ptr + offs)
                tl.store(dst_ptr + offs, vals)
        else:
            mask = offs < n_elements
            vals = tl.load(src_ptr + offs, mask=mask)
            tl.store(dst_ptr + offs, vals, mask=mask)


def _launch_copy(src, dst, n, tile, num_warps):
    num_tiles = (n + tile - 1) // tile
    ncta = _FIXED_CTAS if num_tiles > _FIXED_CTAS else num_tiles
    tiles_per_cta = (num_tiles + ncta - 1) // ncta
    _resize_copy_kernel[(ncta, 1, 1)](
        src,
        dst,
        n,
        tiles_per_cta,
        num_tiles,
        TILE_SIZE=tile,
        EVEN=(n % tile == 0),
        IDX64=(n >= 2**31),
        num_warps=num_warps,
    )


def resize(inp: torch.Tensor, size, memory_format=None):
    out = torch.empty(size, device=inp.device, dtype=inp.dtype)
    n_out = out.numel()
    if n_out == 0:
        return out
    n_in = inp.numel()
    if n_in == 0:
        return out
    # native aten::resize semantics: linear raw-storage prefix copy of
    # min(numel) elements into a freshly allocated contiguous tensor.
    n = n_out if n_out < n_in else n_in
    itemsize = inp.element_size()
    with torch_device_fn.device(inp.device):
        if n <= _SMALL_N:
            _launch_copy(inp, out, n, _SMALL_TILE, _NUM_WARPS)
        elif itemsize == 2:
            if n * 2 >= _BIG_BYTES_16BIT:
                if n % 2 == 0 and inp.is_contiguous() and out.is_contiguous():
                    # widened copy: 256 KiB tiles of int32 units
                    try:
                        src_wide = inp.view(torch.int32)
                        dst_wide = out.view(torch.int32)
                        _launch_copy(
                            src_wide, dst_wide, n // 2, _TILE_BYTES_BIG // 4, _NUM_WARPS
                        )
                        return out
                    except (RuntimeError, TypeError):
                        pass
                _launch_copy(inp, out, n, _TILE_BYTES_BIG // 2, _NUM_WARPS)
            else:
                _launch_copy(inp, out, n, _MED_TILE_16BIT, _NUM_WARPS)
        else:
            tile = _TILE_BYTES_BIG // itemsize if itemsize > 0 else _SMALL_TILE
            if tile < _SMALL_TILE:
                tile = _SMALL_TILE
            _launch_copy(inp, out, n, tile, _NUM_WARPS)
    return out


