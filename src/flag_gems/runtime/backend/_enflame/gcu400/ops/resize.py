# GCU400 customization (2026-11-17):
# 1) Fix grid out-of-range crash: the original implementation used 1 block/CTA with BLOCK_SIZE=1024; when the element
# count > 64Mi
#    grid.x exceeds the hard limit of 65535, aten::resize fails outright with OutOfResources (the 512Mi core bench
#    shape always crashes). Changed to the same Fixed-Grid GSL as the enflame pointwise framework: always 48 CTAs
#    (codegen config max_grid_size=(48,1,1)), each CTA strides over multiple tiles, so any scale
#    stays within the limit; the 1 block/CTA form is also measured to be 30-50× catastrophically worse on GCU (issue
# tax).
# 2) Tiles are dispatched by "256KB/32KB per tile" + dtype (calibrated by measured sweeps): fp32 at all bands
#    TILE=65536; 16-bit at small/medium bands TILE=16384, and the ≥256MB band uses an int32 bit-reinterpret view
#    (a pure view metadata operation) to copy at 256KB/tile; when divisible, take the maskless EVEN branch.
# 3) Clamp the copy count to min(inp.numel(), out.numel()): the original implementation reads src according to
# out.numel(),
#    which reads out of bounds when growing the tensor (a RAS risk on GCU); native aten::resize semantics
#    are a linear prefix copy (the grown tail is uninitialized data); after clamping, semantics match and no
# out-of-bounds access occurs.
