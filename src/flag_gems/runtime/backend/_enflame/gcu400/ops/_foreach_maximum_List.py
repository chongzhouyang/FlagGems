"""GCU400 专属 ``_foreach_maximum_List``（out-of-place ``.List``）。

公共 ``foreach_binary_list`` 用二维 grid 承载 tensor 列表，GCU400 的
``grid.y`` 上限 255 在大 shape 下会 ``out of resource``。本文件早前的
逐 tensor 一维 flat kernel 规避了该问题，但每次调用要为列表里每个
tensor 各发起一次独立 launch：16 个 tensor 的列表仅 ``@libentry`` host
分发开销就恒定在 ~310us（与 shape/dtype 无关），官方 bench 全档
0.16-0.45x，是 clamp/maximum 家族最后一个未单 launch 化的成员。

这里对浮点连续配对列表改走 metadata 融合单次 launch kernel——四段
int64 metadata（输入/输出/第二操作数地址 + 各元素数）按 ``(device,
地址, 元素数)`` 走公共只读缓存，稳态调用（分配器复用同一地址）零
H2D，与 ``_foreach_minimum`` / ``_foreach_clamp_min`` 等已优化同族
一致；广播 ``.List`` 走逐 tensor flat kernel，非浮点 / 非连续 / 异
dtype / 空 tensor 等形态回退公共 ``_apply_list`` 保持 dtype policy
与异常语义。

融合 kernel 的 ``(tensor, part)`` 线性化要求 grid 是 tensor 数的
整数倍（``_foreach_flat._fused_grid`` 在 ``fixed_grid % NT != 0`` 时
会让尾部 tensor 缺 part、漏写奇数 tile），本文件用恒整除的
``_maximum_grid`` 按构造规避（16-tensor 优化器列表 16×256² 直调
对拍实测：非整除 grid 半数张量为垃圾值/NaN，整除后逐位一致）。

冷 L2 归因（官方 do_bench 口径，kernel-only 闭包 9 cell 全档）显示
wrapper 的全部 host 路径已被 launch 流水完全隐藏（host gap ≈ 0），
剩余空间全在 kernel 侧冷带宽：256² 档仅 ~0.95TB/s、512² ~1.7TB/s、
1024² 已贴 2R1W 结构天花板。逐 tile 的 bounds mask 是最大杠杆——
``numel`` 整除 ``BLOCK`` 时免去 load/store 谓词（``EXACT`` 路径），
官方口径交错 A/B：fp32 三档 -17.4%/-9.6%/-4.7%，16-bit 配
``BLOCK=16384`` 后 -7%~-3%（bf16 在 8192 tile 下免 mask 反而
-1.3~-2.8% 回退，16384 tile 下翻正——tile 宽与谓词税存在 dtype
相关耦合，按 dtype 分档取各自最优）。
"""

import logging

import torch
import triton
import triton.language as tl

from flag_gems.ops._foreach_binary import _apply_list
from flag_gems.utils import libentry
from flag_gems.utils.foreach import _device_meta

from ._foreach_flat import (
    _TL_DTYPES,
    FALLBACK,
    MODE_LIST,
    OP_MAX,
    can_use_flat,
    run_binary,
)

logger = logging.getLogger(__name__)

# --- TUNING PARAMS START ---
# Generated by the optimization iteration driver in rounds; all are compile-time/launch-time settings and do not change
# operator semantics.
# Finalized by a single-configuration cold-L2 sweep using the official benchmark protocol (do_bench kernel mode
# w1000/r100)
# (Triton GCU 4.1.6 / flagtree d8ca7a9e, jobs/j20261118092142):
#   * grid must be an integer multiple of the tensor count (see the caveat documented in _maximum_grid);
#   * num_stages 1/2 are identical at every tier (the backend does not pipeline this tile loop); parts>3
#     (grid>48) and nw2/nw8 are all equal or worse;
#   * the divisible path uses EXACT mask-free + BLOCK tiered by dtype: fp32 uses 8192
#     (16384 is slightly worse), 16-bit uses 16384 (8192+EXACT regresses for bf16);
#   * the non-divisible (ragged) path keeps 8192 + mask and is bit-for-bit identical to historical behavior.
FIXED_GRID = 48
BLOCK_SIZE = 8192
BLOCK_SIZE_16BIT = 16384
NUM_WARPS = 4
NUM_STAGES = 1
USE_DEVICE_CONTEXT = 0
# maximum is a selection operation: for same-dtype operands, native-width comparison is bit-for-bit
# consistent with ATen semantics (fp16/bf16 -> fp32 round-trip is lossless), avoiding bidirectional cvt in the hot loop.
FP32_PROMOTE = 0
# When numel is fully divisible by BLOCK, use the mask-free EXACT kernel variant (determined after selecting
# BLOCK by dtype); if any tensor is not divisible, fall back entirely to the mask path.
USE_EXACT = 1
# run_binary only serves broadcast .List (per-tensor kernel); paired lists are all handled by
# _run_maximum_cached. Setting it to 0 ensures run_binary never enters the non-divisible grid path
# of _run_fused (see the caveat documented in _maximum_grid).
FUSED_LAUNCH = 0
FALLBACK_TO_PUBLIC = 0
# Read-only metadata cache: the key contains only device and address/element count, not tensor data; the kernel still
# fully reads inputs and recomputes each time, so address reuse or in-place content changes do not affect correctness.
USE_META_CACHE = 1
# --- TUNING PARAMS END ---


@libentry()
@triton.jit
def _maximum_list_kernel(
    meta_ptr,
    NT: tl.constexpr,
    A_DT: tl.constexpr,
    FP32_PROMOTE: tl.constexpr,
    BLOCK: tl.constexpr,
    EXACT: tl.constexpr,
):
    """``.List`` maximum: one launch covers the whole paired tensor list.

    ``meta_ptr`` holds input pointers, output pointers, second-operand pointers
    and element counts in turn (NT entries each, int64). grid.x is laid out
    linearly as ``(tensor, part)``. It mirrors the shared
    ``fused_binary_list_kernel`` with two differences: OP is fixed to maximum
    (dropping the compile-time dispatch chain) and ``EXACT`` removes the per-tile
    bounds mask when every element count divides ``BLOCK`` -- under the cold-L2
    reference setup that mask predicate is the main kernel-side cost at small
    shapes.
    """
    pid = tl.program_id(0)
    num_programs = tl.num_programs(0)
    tensor_id = pid % NT
    part_id = pid // NT
    num_parts = tl.cdiv(num_programs, NT)

    a_raw = tl.load(meta_ptr + tensor_id)
    out_raw = tl.load(meta_ptr + NT + tensor_id)
    b_raw = tl.load(meta_ptr + 2 * NT + tensor_id)
    num_elems = tl.load(meta_ptr + 3 * NT + tensor_id)

    a_ptr = a_raw.to(tl.pointer_type(A_DT))
    out_ptr = out_raw.to(tl.pointer_type(A_DT))
    b_ptr = b_raw.to(tl.pointer_type(A_DT))

    arange = tl.arange(0, BLOCK)
    num_tiles = tl.cdiv(num_elems, BLOCK)
    for block_id in tl.range(part_id, num_tiles, num_parts):
        offs = block_id * BLOCK + arange
        if EXACT:
            a = tl.load(a_ptr + offs)
            b = tl.load(b_ptr + offs)
            if FP32_PROMOTE:
                a = a.to(tl.float32)
                b = b.to(tl.float32)
            tl.store(out_ptr + offs, tl.maximum(a, b))
        else:
            mask = offs < num_elems
            a = tl.load(a_ptr + offs, mask=mask)
            b = tl.load(b_ptr + offs, mask=mask)
            if FP32_PROMOTE:
                a = a.to(tl.float32)
                b = b.to(tl.float32)
            tl.store(out_ptr + offs, tl.maximum(a, b), mask=mask)


def _maximum_grid(self, fixed_grid, block_size):
    """grid 恒为 tensor 数整除倍：每个 tensor 分到相同的 part 数。

    ``_maximum_list_kernel`` 把一维 grid 线性化为 ``(tensor, part)``：
    ``tensor_id = pid % NT``、``part_id = pid // NT``、
    ``num_parts = cdiv(num_programs, NT)``。当 ``num_programs`` 不是 NT 的
    整数倍时，尾部 tensor 缺 part，按 ``num_parts`` 跨步的 tile 循环会
    跳过无人覆盖的块——``_foreach_flat._fused_grid`` 以 24 grid 承载
    16-tensor 列表时（24 % 16 = 8）实测半数张量奇数 tile 漏写，输出为
    ``empty_like`` 的未初始化内存。这里按构造保证整除。
    """
    num_tensors = len(self)
    blocks_per_tensor = triton.cdiv(max(t.numel() for t in self), block_size)
    parts = max(1, min(fixed_grid // num_tensors, blocks_per_tensor))
    return (num_tensors * parts,)


def _run_maximum_cached(self, other):
    """Lean single-launch path for paired contiguous float lists (cached metadata).

    Unsupported shapes return ``FALLBACK`` and the caller picks the target:
    broadcast ``.List`` needs the per-tensor ``run_binary`` kernel; other shapes
    fall back to the shared executor. The four-part metadata layout (input /
    output / second-operand addresses plus the per-tensor element counts) is
    identical to the fused kernel of ``_foreach_flat``.

    Divisible lists use the mask-free ``EXACT`` variant (BLOCK tiered by dtype:
    8192 for fp32, 16384 for 16-bit); when any tensor's element count does not
    divide the chosen BLOCK the whole list falls back to 8192 with mask, matching
    the historical shipped behaviour.
    """
    if not can_use_flat(self, other, MODE_LIST):
        return FALLBACK
    if not all(o.numel() == t.numel() for t, o in zip(self, other)):
        # Broadcast .List does not share flat indices with the inputs, so hand it to the per-tensor kernel.
        return FALLBACK
    num_tensors = len(self)
    dtype = self[0].dtype
    if USE_EXACT and dtype is not torch.float32:
        block = BLOCK_SIZE_16BIT
    else:
        block = BLOCK_SIZE
    if USE_EXACT and all(t.numel() % block == 0 for t in self):
        exact = 1
    else:
        block = BLOCK_SIZE
        exact = 0
    in_ptrs = [tensor.data_ptr() for tensor in self]
    outputs = [torch.empty_like(tensor) for tensor in self]
    out_ptrs = [tensor.data_ptr() for tensor in outputs]
    b_ptrs = [o.data_ptr() for o in other]
    numels = [tensor.numel() for tensor in self]
    meta = _device_meta(in_ptrs + out_ptrs + b_ptrs + numels, self[0].device)
    grid = _maximum_grid(self, FIXED_GRID, block)
    _maximum_list_kernel[grid](
        meta,
        num_tensors,
        _TL_DTYPES[dtype],
        FP32_PROMOTE,
        block,
        exact,
        num_warps=NUM_WARPS,
        num_stages=NUM_STAGES,
    )
    return outputs


def _foreach_maximum_List(self, other):
    logger.debug("GEMS_GCU400 FOREACH_MAXIMUM_LIST")
    if FALLBACK_TO_PUBLIC:
        return _apply_list("maximum", self, other, False)
    if USE_META_CACHE:
        result = _run_maximum_cached(self, other)
        if result is not FALLBACK:
            return result
    # Broadcast .List (passes can_use_flat but is rejected by the fused path) uses the per-tensor flat
    # kernel; shapes that fail can_use_flat are returned as FALLBACK by run_binary,
    # and handed to the common executor to preserve dtype policy and exception semantics.
    result = run_binary(
        self,
        other,
        OP_MAX,
        MODE_LIST,
        False,
        fixed_grid=FIXED_GRID,
        block_size=BLOCK_SIZE,
        num_warps=NUM_WARPS,
        num_stages=NUM_STAGES,
        use_device_context=USE_DEVICE_CONTEXT,
        fp32_promote=FP32_PROMOTE,
        fused=FUSED_LAUNCH,
    )
    if result is FALLBACK:
        return _apply_list("maximum", self, other, False)
    return result
