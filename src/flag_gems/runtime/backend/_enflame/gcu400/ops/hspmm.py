    """
    Hybrid sparse-dense matrix multiply: mat1 (sparse COO) @ mat2 (dense).

    Args:
        mat1: Sparse COO tensor of shape (M, K)
        mat2: Dense tensor of shape (K, N)

    Returns:
        Sparse COO tensor of shape (M, N), uncoalesced (one entry per input nnz)
    """
